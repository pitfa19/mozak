// plans.md (D3 goal 3, "built regardless"): one generated index per git repository that holds scopes, written at that
// repository's root. Titles and states only: no purposes, outcomes, evidence or decisions, so a private root never
// leaks plan text into it. A repository only lists its own scopes, so a company vault's file never names a personal
// plan and the other way round. Rejected drafts are left out. Read-only except for the plans.md files themselves.

import { existsSync, readFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { mdText, planDisplayState, type PlanDisplayState } from "./bridge.ts";
import { replaceFileDurable } from "./durable.ts";
import { DomainError } from "./errors.ts";
import { findRepoRoot } from "./notes.ts";
import { realOrSelf } from "./paths.ts";
import type { ScopeInventory } from "./scope-index.ts";
import { readScopeQuiet } from "./scope-store.ts";
import type { ScopeState } from "./understanding.ts";

export const PLANS_INDEX_FILE = "plans.md";
export const PLANS_INDEX_MARKER = "<!-- mozak:plans-index v1. Generated by `mozak plans-md`; the next run replaces this file. Do not edit. -->";

const SHOWN: PlanDisplayState[] = ["open", "paused", "awaiting", "completed"];
const STATE_LABEL: Record<string, string> = { open: "open", paused: "paused", awaiting: "awaiting approval", completed: "completed" };

export interface PlansIndexScope {
  id: string;
  /** Scope folder relative to the repository root, "/"-separated; "." for a scope at the root. */
  folder: string;
  status: "ok" | "failed";
  code?: string;
  plans: number;
}

export interface PlansIndexFile {
  repo: string;
  path: string;
  scopes: PlansIndexScope[];
  plans: number;
  /** written: replaced or created. unchanged: same bytes. conflict: an existing plans.md without the marker. printed: not written. */
  result: "written" | "unchanged" | "conflict" | "printed";
  content: string;
}

export interface PlansIndexSkip { scope: string; reason: "repo-mode-remote" | "not-in-git-repo" }

export interface PlansIndexResult { files: PlansIndexFile[]; skipped: PlansIndexSkip[] }

/** The text of one repository's plans.md. Pure. Scopes sorted by folder, plans by state then title then id. */
export function renderPlansIndex(scopes: { id: string; folder: string; state: ScopeState | null }[]): string {
  const lines = [PLANS_INDEX_MARKER, "", "# Plans", "", "Titles and states of the mozak plans in this repository. Each scope's mozak.md has the detail."];
  for (const s of [...scopes].sort((a, b) => a.folder.localeCompare(b.folder) || a.id.localeCompare(b.id))) {
    lines.push("", `## ${mdText(s.state?.scope.title || s.id)}`, "", `Scope \`${s.id}\`, folder \`${s.folder}\`.`, "");
    if (!s.state) { lines.push("- (could not be read)"); continue; }
    const rows = s.state.plans
      .map((p) => ({ p, state: planDisplayState(p), title: (p.accepted ?? p.pending)?.content.title || p.id }))
      .filter((r) => SHOWN.includes(r.state))
      .sort((a, b) => SHOWN.indexOf(a.state) - SHOWN.indexOf(b.state) || a.title.localeCompare(b.title) || a.p.id.localeCompare(b.p.id));
    if (!rows.length) lines.push("- no plans");
    for (const r of rows) lines.push(`- ${STATE_LABEL[r.state]}: ${mdText(r.title)} (${/^[A-Za-z0-9._-]+$/.test(r.p.id) ? `\`${r.p.id}\`` : mdText(r.p.id)})`);
  }
  return `${lines.join("\n")}\n`;
}

/**
 * Build plans.md for every repository in the inventory. `write: false` only returns the text. Never fetches: repo-mode
 * remote scopes are skipped (their plans live in a code repo, not a vault), and scopes outside git are skipped.
 */
export function plansIndex(inv: ScopeInventory, opts: { write: boolean }): PlansIndexResult {
  const byRepo = new Map<string, { id: string; folder: string; state: ScopeState | null; code?: string }[]>();
  const skipped: PlansIndexSkip[] = [];
  for (const entry of inv.scopes) {
    if (entry.remote && entry.remote.plansMode === "repo") { skipped.push({ scope: entry.id, reason: "repo-mode-remote" }); continue; }
    const repo = findRepoRoot(entry.root);
    if (!repo) { skipped.push({ scope: entry.id, reason: "not-in-git-repo" }); continue; }
    const folder = relative(repo, realOrSelf(entry.root)).split(sep).join("/") || ".";
    let state: ScopeState | null = null;
    let code: string | undefined;
    try { state = readScopeQuiet(entry).state; }
    catch (err) { if (!(err instanceof DomainError)) throw err; code = err.code; }
    const list = byRepo.get(repo) ?? [];
    list.push({ id: entry.id, folder, state, ...(code ? { code } : {}) });
    byRepo.set(repo, list);
  }
  const files: PlansIndexFile[] = [];
  for (const [repo, scopes] of [...byRepo].sort((a, b) => a[0].localeCompare(b[0]))) {
    const content = renderPlansIndex(scopes);
    const path = join(repo, PLANS_INDEX_FILE);
    let result: PlansIndexFile["result"] = "printed";
    if (opts.write) {
      const existing = existsSync(path) ? readFileSync(path, "utf8") : null;
      if (existing !== null && !existing.startsWith(PLANS_INDEX_MARKER.slice(0, 26))) result = "conflict";
      else if (existing === content) result = "unchanged";
      else { replaceFileDurable(path, content); result = "written"; }
    }
    const shownScopes: PlansIndexScope[] = scopes.map((s) => ({
      id: s.id, folder: s.folder, status: s.state ? "ok" : "failed", ...(s.code ? { code: s.code } : {}),
      plans: s.state ? s.state.plans.filter((p) => SHOWN.includes(planDisplayState(p))).length : 0,
    }));
    files.push({ repo, path, scopes: shownScopes, plans: shownScopes.reduce((n, s) => n + s.plans, 0), result, content });
  }
  return { files, skipped };
}
